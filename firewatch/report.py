STATUS_LINE = {
    "fixed": "Fixed. The failing tests pass with the patch below.",
    "not_fixed": "Could not produce a passing fix. Here is what was found and tried.",
    "not_reproduced": "The failure did not reproduce on re-run.",
    "no_failure": "Tests already pass.",
    "error": "Stopped because the model could not be reached.",
}


def _fmt_seconds(value):
    return f"{value:.1f}s" if value is not None else "-"


def render_markdown(result, run_url=None, title="Firewatch report"):
    lines = [f"## {title}", "", f"**{STATUS_LINE.get(result.status, result.status)}**", ""]
    if result.diagnosis:
        lines += ["### Root cause", result.diagnosis, ""]
    if result.message and result.status != "fixed":
        lines += [result.message, ""]

    if result.attempts:
        lines += [
            "### Attempts",
            "",
            "| # | Files changed | Failing before → after | Kept | Model time | Test time |",
            "|---|---|---|---|---|---|",
        ]
        for a in result.attempts:
            files = ", ".join(f"`{f}`" for f in a.files_changed) or "none"
            after = "-" if a.failed_after is None else str(a.failed_after)
            kept = "yes" if a.kept else "no"
            lines.append(
                f"| {a.number} | {files} | {a.failed_before} → {after} | {kept} | "
                f"{_fmt_seconds(a.model_seconds)} | {_fmt_seconds(a.test_seconds)} |"
            )
        rejected = [e for a in result.attempts for e in a.edit_errors]
        if rejected:
            lines += ["", "<details><summary>Rejected edits</summary>", ""]
            lines += [f"- {e}" for e in rejected]
            lines += ["", "</details>"]
        lines.append("")

    if result.final_diff.strip():
        heading = "### Patch" if result.fixed else "### Last change tried"
        lines += [heading, "", "```diff", result.final_diff.rstrip(), "```", ""]

    if result.failure_excerpt:
        lines += [
            "<details><summary>Original failure</summary>",
            "",
            "```",
            result.failure_excerpt[-6000:].rstrip(),
            "```",
            "",
            "</details>",
            "",
        ]

    footer = f"Model: `{result.model}` · Total time {result.duration:.0f}s"
    if run_url:
        footer += f" · [Failed run]({run_url})"
    lines += ["---", f"<sub>{footer} · Generated by Firewatch, verified by re-running your tests before reporting.</sub>"]
    return "\n".join(lines)
